import json
import re
from collections.abc import Callable
from types import SimpleNamespace
from typing import Any

from research_agents.models import TokenUsage
from research_agents.ports import JsonRequest
from research_agents.prompts import REPORT, SEARCH_PLAN

TOPIC_LINE = re.compile(r"^(?:Research topic|Topic): (?P<topic>.+)$", re.MULTILINE)
SOURCE_LINE = re.compile(r"^\[(?P<id>[^\]]+)\] (?P<title>.+) \((?P<published>[^)]*)\)$", re.MULTILINE)
MAX_CITED = 6


class FakeJsonLlm:
    """Deterministic stand-in for Claude, selected with `RA_LLM_PROVIDER=fake`.

    It honours the same contract as the real client (schema-shaped JSON plus token usage) and builds its
    answers only from the prompt, so the whole platform - Kafka, orchestration, citation checks, vector
    search, storage and metrics - can be run end to end locally and in CI without an API key or cost.
    """

    def __init__(self) -> None:
        self._builders: dict[str, Callable[[str], dict[str, Any]]] = {
            SEARCH_PLAN: _search_plan,
            REPORT: _report,
        }

    def complete(self, request: JsonRequest, messages: list[dict[str, Any]], usage: TokenUsage) -> str:
        prompt = messages[0]["content"]
        answer = json.dumps(self._builders[request.name](prompt))
        usage.add(SimpleNamespace(input_tokens=len(prompt) // 4, output_tokens=len(answer) // 4))
        return answer


def _topic(prompt: str) -> str:
    match = TOPIC_LINE.search(prompt)
    return match.group("topic").strip() if match else prompt.strip()


def _search_plan(prompt: str) -> dict[str, Any]:
    topic = _topic(prompt)
    return {"queries": [topic, f"{topic} benchmark", f"{topic} survey"]}


def _report(prompt: str) -> dict[str, Any]:
    topic = _topic(prompt)
    sources = [(m.group("id"), m.group("title")) for m in SOURCE_LINE.finditer(prompt)][:MAX_CITED]
    ids = [source_id for source_id, _ in sources]
    overview = f"This report summarises {len(ids)} papers on {topic} [{', '.join(ids[:2])}]."
    findings = " ".join(f"{title} [{source_id}]." for source_id, title in sources)
    return {
        "title": f"Research report: {topic}",
        "summary": overview,
        "sections": [
            {"heading": "Key papers", "body": findings},
            {"heading": "Note", "body": "Generated by the offline fake LLM provider for local testing."},
        ],
        "cited_ids": ids,
    }
